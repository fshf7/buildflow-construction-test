export const ACTION_LABELS: Record<string, string> = {
  INSERT: "Создание",
  UPDATE: "Изменение",
  DELETE: "Удаление",
  MFA_RESET: "Сброс второго фактора",
  PASSWORD_RESET: "Сброс пароля",
};

const IGNORED_FIELDS = new Set(["updated_at", "created_at", "created_by", "id", "organization_id"]);

/** Какие поля изменились (для UPDATE) — без служебных, по-русски. */
export function changedFields(
  oldData: Record<string, unknown> | null,
  newData: Record<string, unknown> | null,
): string[] {
  if (!oldData || !newData) return [];
  return Object.keys(newData)
    .filter(
      (k) => !IGNORED_FIELDS.has(k) && JSON.stringify(oldData[k]) !== JSON.stringify(newData[k]),
    )
    .map((k) => FIELD_LABELS[k] ?? k);
}

/** Короткое описание записи: название/ФИО/номер/код, если есть. */
export function recordTitle(data: Record<string, unknown> | null): string | null {
  if (!data) return null;
  for (const key of ["name", "full_name", "title", "number", "code", "email"]) {
    const v = data[key];
    if (typeof v === "string" && v) return v;
  }
  return null;
}

/** Пояснение для особых событий (например, причина сброса второго фактора). */
export function eventDetails(
  action: string,
  newData: Record<string, unknown> | null,
): string | null {
  if ((action === "MFA_RESET" || action === "PASSWORD_RESET") && newData) {
    const via = newData.via === "script" ? " (серверный скрипт)" : "";
    return `Причина: ${String(newData.reason ?? "—")}${via}`;
  }
  return null;
}
