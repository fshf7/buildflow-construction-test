import "server-only";

import { revalidatePath } from "next/cache";

/**
 * После проведения или изменения документа: сбросить кэш маршрутизатора для всех страниц.
 * Документ виден сразу в нескольких местах (объект, «Общее», отчёты — Д-94), а страницы
 * и так рендерятся на запрос (Д-81), поэтому точечные пути не нужны.
 */
export function revalidateApp(): void {
  revalidatePath("/", "layout");
}
